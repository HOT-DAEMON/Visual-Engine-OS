import { writeFileSync } from 'node:fs';
import { Resvg } from '@resvg/resvg-js';
import { ARCHETYPES, BodyParams, type BodyInput } from '../src/body';
import { bodyVolumes, renderVolumesPixel } from '../src/body/volume';
import { bodyHost } from './lib/body-host';
const H = bodyHost(), pose = { abduction: 10, forearmSwing: 4, elbowFlex: 23, wristDev: 0, pronation: -0.65 };
const b: any = JSON.parse(JSON.stringify(BodyParams.parse(ARCHETYPES.veryMuscular))); for (const sd of ['left', 'right']) Object.assign(b.pose[sd], pose);
const yaw = Number(process.argv[2] ?? 0), set = bodyVolumes(b as BodyInput, H.a, {}), m = renderVolumesPixel(set, { skin: H.skin, heightPx: 1100, camera: { yaw, pitch: -2, pivot: { x: 0, y: 0, z: 0 } }, uid: 'v' });
const bd = m.bounds, w = bd.x1 - bd.x0, h = bd.y1 - bd.y0;
const crop = process.argv[3] === 'shoulder' ? `${bd.x0 + w * 0.05} ${bd.y0} ${w * 0.5} ${h * 0.38}` : `${bd.x0} ${bd.y0} ${w} ${h}`;
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${crop}" width="900"><rect x="${bd.x0}" y="${bd.y0}" width="${w}" height="${h}" fill="#3b4157"/>${m.svg}</svg>`;
writeFileSync(process.argv[4] ?? '/home/claude/work/view.png', new Resvg(svg).render().asPng());
